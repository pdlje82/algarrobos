const {chromium} = require('C:/Users/JanEngelke/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const {pathToFileURL} = require('url');
(async () => {
  const here = __dirname;
  const root = path.resolve(here, '../..');
  const temporary = path.join(root, 'tmp/pdfs/al20-score-optimisation');
  fs.mkdirSync(temporary, {recursive:true});
  const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page = await browser.newPage({viewport:{width:1440,height:1060},deviceScaleFactor:1});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(here, 'Revision y puntuacion.html')).href);
  await page.screenshot({path:path.join(temporary,'review-desktop.png')});
  await page.locator('#chapter-2').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(temporary,'park-vision.png')});
  await page.locator('#pasos').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(temporary,'open-decisions.png')});
  await page.locator('#solicitud').evaluate(element=>{element.open=true});
  await page.locator('#solicitud').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(temporary,'application-desktop.png')});
  const desktop = await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,tables:document.querySelectorAll('table').length,headings:document.querySelectorAll('h2').length,narrativeChapters:document.querySelectorAll('.chapter').length,openingTitle:document.querySelector('.chapter h2').textContent,openDecisionsAfterSixChapters:document.querySelector('#pasos').previousElementSibling.querySelectorAll('.chapter').length===6,brokenLocalLinks:[...document.querySelectorAll('a[href]')].filter(a=>a.getAttribute('href').startsWith('#')&&!document.getElementById(a.getAttribute('href').slice(1))).length}));
  await page.setViewportSize({width:390,height:844});
  await page.goto(pathToFileURL(path.join(here,'Revision y puntuacion.html')).href);
  await page.screenshot({path:path.join(temporary,'review-mobile.png')});
  const mobile = await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  await page.setViewportSize({width:900,height:1060});
  await page.goto(pathToFileURL(path.join(temporary,'EPUB/chapter-01.xhtml')).href);
  await page.screenshot({path:path.join(temporary,'listening-chapter.png')});
  const chapter = await page.evaluate(()=>({title:document.title,language:document.documentElement.lang,paragraphs:document.querySelectorAll('p').length,text:document.body.innerText.length}));
  await browser.close();
  if(errors.length||desktop.brokenLocalLinks||desktop.scrollWidth>desktop.width||mobile.scrollWidth>mobile.width||desktop.narrativeChapters!==8||!desktop.openDecisionsAfterSixChapters)throw new Error(JSON.stringify({errors,desktop,mobile}));
  fs.writeFileSync(path.join(here,'Revision visual.json'),JSON.stringify({date:'2026-11-03',browser:'Installed Microsoft Edge, local rendering',desktop,mobile,chapter,errors,direct_elevenreader_playback_checked:false,visual_inspection:'Screenshots produced for agent inspection; results recorded separately in completion review.'},null,2)+'\n');
  process.stdout.write(JSON.stringify({desktop,mobile,chapter,errors}));
})().catch(e=>{process.stderr.write(e.stack);process.exitCode=1});
